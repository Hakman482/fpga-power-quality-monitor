                        current_sample_reg <=
                            CURRENT_LOW_FREQ_LUT(
                                phase_sample_reg
                            );



                    --------------------------------------------------
                    -- HIGH FREQUENCY
                    --
                    -- Direct 195-sample sinusoid.
                    --------------------------------------------------

                    elsif event_reg = 6 then


                        voltage_sample_reg <=
                            VOLTAGE_HIGH_FREQ_LUT(
                                phase_sample_reg
                            );


                        current_sample_reg <=
                            CURRENT_HIGH_FREQ_LUT(
                                phase_sample_reg
                            );



                    --------------------------------------------------
                    -- 50 Hz EVENTS
                    --------------------------------------------------

                    else


                        ------------------------------------------------
                        -- Default magnitudes
                        ------------------------------------------------

                        voltage_magnitude :=
                            VOLTAGE_NORMAL_LUT(
                                quarter_lut_index_reg
                            );


                        current_magnitude :=
                            CURRENT_NORMAL_LUT(
                                quarter_lut_index_reg
                            );



                        ------------------------------------------------
                        -- Event-specific amplitude/waveform
                        ------------------------------------------------

                        case event_reg is


                            when 1 =>

                                voltage_magnitude :=
                                    VOLTAGE_SAG_LUT(
                                        quarter_lut_index_reg
                                    );


                            when 3 =>

                                voltage_magnitude :=
                                    VOLTAGE_SWELL_LUT(
                                        quarter_lut_index_reg
                                    );


                            when 7 =>

                                voltage_magnitude :=
                                    VOLTAGE_THD_LUT(
                                        quarter_lut_index_reg
                                    );


                            when 8 =>

                                current_magnitude :=
                                    CURRENT_THD_LUT(
                                        quarter_lut_index_reg
                                    );


                            when others =>

                                null;


                        end case;



                        ------------------------------------------------
                        -- Apply sine-wave sign
                        ------------------------------------------------

                        if negative_reg = '1' then


                            voltage_sample_reg <=
                                -voltage_magnitude;


                            current_sample_reg <=
                                -current_magnitude;


                        else


                            voltage_sample_reg <=
                                voltage_magnitude;


                            current_sample_reg <=
                                current_magnitude;


                        end if;


                    end if;


                    stage3_pending <=
                        '1';


                    stage2_pending <=
                        '0';


                end if;



                ------------------------------------------------------
                -- SAMPLE TICK GENERATOR
                ------------------------------------------------------

                if sample_clock_counter =
                   CLKS_PER_SAMPLE - 1
                then


                    sample_clock_counter <=
                        0;



                    --------------------------------------------------
                    -- PIPELINE STAGE 1
                    --
                    -- Save the exact phase index used for this
                    -- particular sample.
                    --------------------------------------------------

                    phase_sample_reg <=
                        phase_index;


                    event_reg <=
                        event_state;



                    --------------------------------------------------
                    -- For 50 Hz states, convert the 200-sample phase
                    -- index to quarter-wave address and sign.
                    --
                    -- Frequency states use the full-cycle ROMs and
                    -- therefore do not require this mapping.
                    --------------------------------------------------

                    if
                        event_state /= 5
                        and
                        event_state /= 6
                    then


                        if phase_index <= 50 then


                            quarter_lut_index_reg <=
                                phase_index;


                            negative_reg <=
                                '0';



                        elsif phase_index <= 100 then


                            quarter_lut_index_reg <=
                                100 - phase_index;


                            negative_reg <=
                                '0';



                        elsif phase_index <= 150 then


                            quarter_lut_index_reg <=
                                phase_index - 100;


                            negative_reg <=
                                '1';



                        else


                            quarter_lut_index_reg <=
                                200 - phase_index;


                            negative_reg <=
                                '1';


                        end if;


                    else


                        quarter_lut_index_reg <=
                            0;


                        negative_reg <=
                            '0';


                    end if;


                    stage2_pending <=
                        '1';



                    --------------------------------------------------
                    -- EVENT TIMER
                    --------------------------------------------------

                    if event_sample_counter =
                       EVENT_SAMPLES - 1
                    then


                        event_sample_counter <=
                            0;



                        ------------------------------------------------
                        -- Advance event
                        ------------------------------------------------

                        if event_state = 9 then


                            event_state <=
                                0;


                        else


                            event_state <=
                                event_state + 1;


                        end if;



                        ------------------------------------------------
                        -- Restart phase at every event transition.
                        ------------------------------------------------

                        phase_index <=
                            0;



                    else


                        event_sample_counter <=
                            event_sample_counter + 1;



                        ------------------------------------------------
                        -- PHASE ADVANCEMENT
                        ------------------------------------------------

                        case event_state is



                            --------------------------------------------
                            -- LOW FREQUENCY
                            --
                            -- Exactly 205 samples/cycle.
                            --------------------------------------------

                            when 5 =>


                                if phase_index =
                                   LOW_FREQ_PHASE_POINTS - 1
                                then


                                    phase_index <=
                                        0;


                                else


                                    phase_index <=
                                        phase_index + 1;


                                end if;



                            --------------------------------------------
                            -- HIGH FREQUENCY
                            --
                            -- Exactly 195 samples/cycle.
                            --------------------------------------------

                            when 6 =>


                                if phase_index =
                                   HIGH_FREQ_PHASE_POINTS - 1
                                then


                                    phase_index <=
                                        0;


                                else


                                    phase_index <=
                                        phase_index + 1;


                                end if;



                            --------------------------------------------
                            -- All remaining events:
                            -- exactly 200 samples/cycle.
                            --------------------------------------------

                            when others =>


                                if phase_index =
                                   NOMINAL_PHASE_POINTS - 1
                                then


                                    phase_index <=
                                        0;


                                else


                                    phase_index <=
                                        phase_index + 1;


                                end if;


                        end case;


                    end if;



                else


                    sample_clock_counter <=
                        sample_clock_counter + 1;


                end if;


            end if;


        end if;


    end process;


end architecture rtl;